// Writes src/lib/whiteboard/icon-data.ts: the drawing data of every icon
// named in src/lib/whiteboard/icons.ts, copied out of the installed
// lucide-react. Run it after changing that list or upgrading lucide-react:
//
//   node scripts/generate-whiteboard-icons.mjs
//
// The data is checked in, so the image renderer can draw an icon on the
// server without React, and the canvas ships these icons only.

import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath, pathToFileURL } from "node:url"

const root = fileURLToPath(new URL("..", import.meta.url))
const list = readFileSync(`${root}src/lib/whiteboard/icons.ts`, "utf8")
const names = [...list.matchAll(/\bicon\("([a-z0-9-]+)"/g)].map((match) => match[1])

const entries = []
for (const name of [...new Set(names)].sort()) {
  const file = `${root}node_modules/lucide-react/dist/esm/icons/${name}.mjs`
  const { __iconData } = await import(pathToFileURL(file).href)
  // React's list key means nothing outside React.
  const node = __iconData.node.map(([tag, attributes]) => [
    tag,
    Object.fromEntries(Object.entries(attributes).filter(([name]) => name !== "key")),
  ])
  entries.push(`  ${JSON.stringify(name)}: ${JSON.stringify(node)},`)
}

writeFileSync(
  `${root}src/lib/whiteboard/icon-data.ts`,
  `// Generated by scripts/generate-whiteboard-icons.mjs from lucide-react (ISC). Do not edit.

// One drawing instruction: an SVG element name and its attributes, on
// Lucide's 24 by 24 grid, stroked two units wide with round caps and joins.
export type IconNode = [tag: string, attributes: Record<string, string>][]

export const ICON_NODES: Record<string, IconNode> = {
${entries.join("\n")}
}
`
)
console.log(`Wrote ${entries.length} icons.`)
